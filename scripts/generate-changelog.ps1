# generate-changelog.ps1
#
# Genera CHANGELOG.md desde los commits del repositorio siguiendo
# el formato de Conventional Commits.
#
# Alternativa a git-cliff si no está instalado.
#
# Uso:
#   .\scripts\generate-changelog.ps1

$ErrorActionPreference = "Stop"

$output = "CHANGELOG.md"

$tipos = [ordered]@{
    "feat"     = "Features"
    "fix"      = "Bug Fixes"
    "docs"     = "Documentation"
    "perf"     = "Performance"
    "refactor" = "Refactor"
    "test"     = "Testing"
    "build"    = "Build System"
    "ci"       = "CI/CD"
    "chore"    = "Miscellaneous Tasks"
    "revert"   = "Revert"
}

$header = @"
# Changelog

Todos los cambios notables de AquaPort se documentan en este archivo.
Formato basado en [Keep a Changelog](https://keepachangelog.com/).
Los commits siguen [Conventional Commits](https://www.conventionalcommits.org/).

"@

$body = ""

foreach ($entry in $tipos.GetEnumerator()) {
    $tipo = $entry.Key
    $grupo = $entry.Value

    # Filtra commits por tipo, sin merges, más recientes primero
    $commits = git log --no-merges --pretty=format:"%s" --grep="^$tipo" 2>$null

    if ($commits) {
        $body += "### $grupo`n`n"
        foreach ($commit in $commits) {
            $body += "- $commit`n"
        }
        $body += "`n"
    }
}

$body += "<!-- generated by scripts/generate-changelog.ps1 -->`n"

$header + $body | Out-File -FilePath $output -Encoding UTF8

Write-Host "CHANGELOG generado en $output" -ForegroundColor Green
Write-Host "Lineas: $((Get-Content $output).Count)" -ForegroundColor Cyan